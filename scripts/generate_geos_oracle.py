"""Generate finite GEOS comparison fixtures; Shapely is a development tool only.

Install shapely==2.2.0 separately, then run this script or pass --check.
Coordinates are small integers; this is not a test of extreme floating inputs.
"""
from __future__ import annotations

import argparse
import random
import re
from pathlib import Path

import shapely
from shapely.geometry import LineString, Point, Polygon

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "geos_oracle_test.mbt"
SEED = 20261030


def segment(a, b):
    return Point(a) if a == b else LineString([a, b])


def relation(a, b, c, d):
    intersection = segment(a, b).intersection(segment(c, d))
    if intersection.is_empty:
        return 0
    if intersection.geom_type != "Point":
        return 3
    p = (intersection.x, intersection.y)
    return 1 if p in (a, b, c, d) else 2


def generate():
    if shapely.__version__ != "2.2.0":
        raise SystemExit("Use shapely==2.2.0 to reproduce this fixture")
    rng = random.Random(SEED)
    cases = []
    for _ in range(500):
        points = [(rng.randint(-7, 7), rng.randint(-7, 7)) for _ in range(4)]
        cases.append((*[v for p in points for v in p], relation(*points)))
    # Explicitly exercise overlap, endpoint touch and point segments.
    for points in [((0, 0), (4, 0), (2, 0), (6, 0)),
                   ((0, 0), (2, 0), (2, 0), (4, 0)),
                   ((1, 1), (1, 1), (0, 1), (2, 1))]:
        cases.append((*[v for p in points for v in p], relation(*points)))

    shells = [
        ([(0, 0), (10, 0), (10, 10), (0, 10)], []),
        ([(0, 0), (10, 0), (10, 10), (0, 10)], [[(2, 2), (4, 2), (4, 4), (2, 4)]]),
        ([(0, 0), (6, 0), (6, 2), (2, 2), (2, 6), (0, 6)], []),
    ]
    polygons = [Polygon(shell, holes) for shell, holes in shells]
    assert all(p.is_valid for p in polygons)
    probes = []
    for i, poly in enumerate(polygons):
        for x in range(-1, 12):
            for y in range(-1, 12):
                p = Point(x, y)
                label = 1 if poly.boundary.covers(p) else 2 if poly.contains(p) else 0
                probes.append((i, x, y, label))

    out = ["// Generated by scripts/generate_geos_oracle.py with Shapely 2.2.0.",
           "///|", 'test "GEOS segment classifications on small integer coordinates" {',
           "  let cases : Array[(Int32, Int32, Int32, Int32, Int32, Int32, Int32, Int32, Int32)] = ["]
    out += ["    (" + ", ".join(map(str, row)) + ")," for row in cases]
    out += ["  ]", "  for c in cases {",
            "    let a = @moon-geo.Segment::new(@moon-geo.Point::new(c.0.to_double(), c.1.to_double()), @moon-geo.Point::new(c.2.to_double(), c.3.to_double()))",
            "    let b = @moon-geo.Segment::new(@moon-geo.Point::new(c.4.to_double(), c.5.to_double()), @moon-geo.Point::new(c.6.to_double(), c.7.to_double()))",
            "    let value = match @moon-geo.segment_relation(a, b) { @moon-geo.Disjoint => 0; @moon-geo.Touch(_) => 1; @moon-geo.Cross => 2; @moon-geo.Overlap(_) => 3 }",
            "    assert_eq(value, c.8)", "  }", "}", "///|",
            'test "GEOS polygon point locations including holes and boundaries" {',
            "  let polygons = ["]
    def points(items):
        return "[" + ", ".join(f"@moon-geo.Point::new({x}.0, {y}.0)" for x, y in items) + "]"
    for shell, holes in shells:
        holes_arg = "[" + ", ".join(points(hole) for hole in holes) + "]"
        out.append(f"    @moon-geo.Polygon::new({points(shell)}, holes={holes_arg}),")
    out += ["  ]", "  let cases : Array[(Int32, Int32, Int32, Int32)] = ["]
    out += ["    (" + ", ".join(map(str, row)) + ")," for row in probes]
    out += ["  ]", "  for c in cases {",
            "    let p = @moon-geo.Point::new(c.1.to_double(), c.2.to_double())",
            "    let location = polygons[c.0].locate(p).location",
            "    let value = match location { @moon-geo.Outside => 0; @moon-geo.OnBoundary => 1; @moon-geo.Inside => 2 }",
            "    assert_eq(value, c.3)", "  }", "}", ""]
    return "\n".join(out), len(cases), len(probes)


def normalize(text):
    return re.sub(r",(?=[)\]])", "", re.sub(r"[\s;]+", "", text))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected, segments, probes = generate()
    if args.check:
        assert normalize(OUTPUT.read_text(encoding="utf-8")) == normalize(expected), "fixture drift"
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Shapely {shapely.__version__}, GEOS {shapely.geos_version_string}: {segments} segment pairs, {probes} polygon points; seed={SEED}; {'verified' if args.check else 'generated'}")


if __name__ == "__main__":
    main()
