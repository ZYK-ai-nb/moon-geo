"""Generate independent exact-sign fixtures using only Python's standard library.

MoonGeo does not use this script at runtime. Fraction.from_float preserves the
actual binary input, rather than treating its printed decimal as an exact value.
Run with --check to verify committed fixtures without changing them.
"""
from __future__ import annotations

import argparse
from fractions import Fraction
import json
import math
from pathlib import Path
import random
import re

ROOT = Path(__file__).resolve().parents[1]
SEED = 20261029


def exact_sign(coords: list[float]) -> int:
    ax, ay, bx, by, cx, cy = map(Fraction.from_float, coords)
    det = (bx - ax) * (cy - ay) - (by - ay) * (cx - ax)
    return (det > 0) - (det < 0)


def literal(value: float) -> str:
    return re.sub(r"^(-?\d+)e", r"\1.0e", repr(value))


def fixtures() -> list[dict]:
    rng = random.Random(SEED)
    cases: list[dict] = []
    initial = [
        [0., 0., 1., 0., 0., 1.],
        [0., 0., 134217728., 134217729., 134217729., 134217730.],
        [0., 0., 1e-200, 0., 0., 1e-200],
        [0., 0., math.ulp(0.), 0., 0., math.ulp(0.)],
        [-1e100, -1e100, 0., 0., 1e100, 1e100],
        [-0., 0., 0., -0., 1., 2.],
    ]
    for i in range(180):
        if i < len(initial):
            coords = initial[i]
        elif i % 4 == 0:
            n = float(rng.randrange(2**26, 2**40))
            points = [(0., 0.), (n, n + 1.), (n + 1., n + 2.)]
            rng.shuffle(points)
            coords = [v for p in points for v in p]
        elif i % 4 == 1:
            coords = [math.ldexp(rng.uniform(-1., 1.), rng.randint(-1074, 330)) for _ in range(6)]
        elif i % 4 == 2:
            scale = rng.randint(-1000, 290)
            coords = [math.ldexp(float(rng.randint(-1000, 1000)), scale) for _ in range(6)]
        else:
            x, y = rng.uniform(-1e8, 1e8), rng.uniform(-1e8, 1e8)
            coords = [0., 0., x, y, 2. * x, math.nextafter(2. * y, math.inf)]
        assert all(math.isfinite(v) and abs(v) <= 1e100 for v in coords)
        cases.append({"coordinates": coords, "sign": exact_sign(coords)})
    return cases


def outputs() -> dict[Path, str]:
    cases = fixtures()
    lines = [
        "// Generated by scripts/generate_oracle.py; do not edit expected signs.",
        "///|", 'test "180 independent Python Fraction orientation fixtures" {',
        "  let cases : Array[(Double, Double, Double, Double, Double, Double, Int)] = [",
    ]
    for case in cases:
        values = [literal(v) for v in case["coordinates"]] + [str(case["sign"])]
        lines.append("    (" + ", ".join(values) + "),")
    lines += [
        "  ]", "  for c in cases {",
        "    let actual = @moon-geo.orientation(",
        "      @moon-geo.Point::new(c.0,c.1), @moon-geo.Point::new(c.2,c.3), @moon-geo.Point::new(c.4,c.5),",
        "    )",
        "    let sign = match actual { @moon-geo.CW => -1; @moon-geo.Collinear => 0; @moon-geo.CCW => 1 }",
        "    assert_eq(sign,c.6)", "  }", "}", "",
    ]
    manifest = {"generator": "Python Fraction.from_float", "seed": SEED, "cases": cases}
    return {
        ROOT / "orientation_oracle_test.mbt": "\n".join(lines),
        ROOT / "testdata" / "orientation_oracle.json": json.dumps(manifest, indent=2, allow_nan=False) + "\n",
    }


def generated_cases(text: str) -> list[dict]:
    """Parse only the fixture constants, tolerating moon fmt's whitespace."""
    match = re.search(r"let cases\s*:\s*Array.*?=\s*\[(.*?)\]\s*for c", text, re.S)
    assert match is not None, "missing generated fixture array"
    parsed = []
    for record in re.findall(r"\(([^()]*)\)", match.group(1)):
        tokens = [part.strip() for part in record.split(",") if part.strip()]
        assert len(tokens) == 7, "malformed generated fixture"
        parsed.append({"coordinates": [float(v) for v in tokens[:6]], "sign": int(tokens[6])})
    return parsed


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in outputs().items():
        if args.check:
            if path.suffix == ".json":
                assert path.read_text(encoding="utf-8") == expected, f"fixture drift: {path}"
            else:
                actual = generated_cases(path.read_text(encoding="utf-8"))
                assert len(actual) == len(fixtures()), "fixture count drift"
                for a, b in zip(actual, fixtures(), strict=True):
                    assert [v.hex() for v in a["coordinates"]] == [v.hex() for v in b["coordinates"]], "coordinate drift"
                    assert a["sign"] == b["sign"], "expected sign drift"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
    print(f"orientation oracle: {len(fixtures())} cases; seed={SEED}; " + ("verified" if args.check else "generated"))


if __name__ == "__main__":
    main()
